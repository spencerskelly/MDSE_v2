#!/usr/bin/env node
// Builds the Testbench Obsidian plugin (D-0170) from tools/testbench/src plus the shared Workbench and core modules it
// reuses (index, views, flows, the database layer). Same bundling rules as tools/workbench/build.mjs: modules share one
// scope; `import * as X` becomes an object of the module's exports. `--check` exits 1 if the committed output is stale.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { stripTypeScriptTypes } from "node:module";
const here = path.dirname(fileURLToPath(import.meta.url));
const rd = (p) => fs.readFileSync(path.join(here, p), "utf8");
const strip = (s) => s.replace(/\nif \(typeof module !== "undefined"\)[^\n]*\n?$/, "\n");
const CORE = strip(rd("../core/src/mdse_core.js"));
const CLASSES = JSON.stringify(JSON.parse(rd("../core/src/classes.json")));
// paths relative to tools/testbench; order matters only for top-level code
const ORDER = ["../importer/src/sha256", "../core/src/mdse_db", "../workbench/src/sysml_lang", "../workbench/src/sysml_scan", "../workbench/src/index", "../workbench/src/views", "../workbench/src/edit",
  "../workbench/src/flow_defs", "../workbench/src/flows", "src/dom", "../workbench/src/flows_ui", "../workbench/src/flow_guide", "src/tb_csv", "src/tb_run", "src/tb_db", "src/tb_pair", "src/tb_view"];
const base = (p) => p.slice(p.lastIndexOf("/") + 1);
const exportsOf = (code) => [...code.matchAll(/^export (?:async )?(?:function|const|class|interface|type)\s+(\w+)/gm)].map((m) => m[1]);
const names = new Map(), parts = [], declared = new Set();
for (const n of ORDER) { const raw = rd(`${n}.ts`); names.set(base(n), exportsOf(raw).filter((x) => !new RegExp(`export (?:interface|type) ${x}\\b`).test(raw))); }
for (const n of ORDER) {
  let code = rd(`${n}.ts`);
  code = code.replace(/^import \* as (\w+) from "([^"]+)\.ts";\s*$/gm, (_, ns, mod) => {
    const m = base(mod), k = `${ns}:${m}`; if (declared.has(k)) return "";
    if (!names.has(m)) throw new Error(`${n}.ts imports ${mod}.ts, which is not in ORDER`);
    declared.add(k); return `const ${ns} = { ${names.get(m).join(", ")} };`;
  });
  code = code.replace(/^import MDSE from [^;]*;\s*$/gm, "").replace(/^import (?:type )?\{[^}]*\} from [^;]*;\s*$/gm, "").replace(/^import type [^;]*;\s*$/gm, "").replace(/^export type \{[^}]*\}( from [^;]*)?;\s*$/gm, "")
    .replace(/^export (?=(async |function|const|class|interface|type))/gm, "");
  parts.push(`/* ${n}.ts */\n` + stripTypeScriptTypes(code, { mode: "strip" }));
}
const api = "{ mountTestbench, buildIndexAsync, openTestbenchDb, indexRuns, saveRunDraft, base64Bytes, TB_DB_PATH, edAuthor, openPairSession, listRuns, parseReport, flowDefs, Sha256, renderGuide, guidePath, guideNeedsWrite, isIndexedPath, isGovernedText }";
const tb = `const TB = (() => {\n${parts.join("\n")}\nreturn ${api};\n})();`;
const SQLJS = "/* sql.js 1.17.0, MIT, vendored unmodified from tools/core/vendor/sqljs (D-0170) */\nconst initSqlJs = (() => { var module = { exports: {} }; var exports = module.exports;\n"
  + rd("../core/vendor/sqljs/sql-wasm.js") + "\n;return module.exports; })();\nconst SQLJS_WASM_B64 = \"" + fs.readFileSync(path.join(here, "../core/vendor/sqljs/sql-wasm.wasm")).toString("base64") + "\";\n";
const QR = "/* qrcode-generator 1.5.2, MIT, vendored unmodified from tools/core/vendor/qrcode-generator (D-0170) */\nconst qrcode = (() => { var module = { exports: {} }; var exports = module.exports; var define = undefined;\n"
  + rd("../core/vendor/qrcode-generator/qrcode.js") + "\n;return module.exports; })();\n";
const version = JSON.parse(rd("manifest.json")).version;
const plugin = `/* MDSE Testbench ${version} — generated by tools/testbench/build.mjs. Do not edit. */\n${CORE}\nconst CLASSES = ${CLASSES};\n${tb}\n${SQLJS}${QR}` + stripTypeScriptTypes(rd("src/plugin.ts"), { mode: "strip" });
const outputs = { "dist/plugin/main.js": plugin, "dist/plugin/manifest.json": rd("manifest.json"), "dist/plugin/styles.css": "/* styles are injected by the view */\n" };
let stale = false;
for (const [p, text] of Object.entries(outputs)) {
  const f = path.join(here, p);
  if (process.argv.includes("--check")) { if (!fs.existsSync(f) || fs.readFileSync(f, "utf8") !== text) { console.error(`${p} is out of date; run: npm run build:testbench`); stale = true; } }
  else { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, text); console.log(`wrote tools/testbench/${p} (${(text.length / 1024).toFixed(0)} KiB)`); }
}
if (stale) process.exit(1); else if (process.argv.includes("--check")) console.log("testbench output is current");
