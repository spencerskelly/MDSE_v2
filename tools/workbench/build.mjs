#!/usr/bin/env node
// Builds the Workbench: one offline HTML page and an Obsidian plugin folder, both from the same TypeScript.
// `--check` exits 1 if the committed output is stale (CI).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { stripTypeScriptTypes } from "node:module";
const here = path.dirname(fileURLToPath(import.meta.url));
const rd = (p) => fs.readFileSync(path.join(here, p), "utf8");
const strip = (s) => s.replace(/\nif \(typeof module !== "undefined"\)[^\n]*\n?$/, "\n");
const CORE = strip(rd("../core/src/mdse_core.js"));
const CLASSES = JSON.stringify(JSON.parse(rd("../core/src/classes.json")));
const ORDER = ["../../importer/src/sha256", "../../core/src/bom_own", "sysml_lang","sysml_scan", "index", "views", "canvas", "edit", "canvas_draw", "edit_rel", "edit_port", "merge_ops", "edit_help", "vault_files", "ui", "edit_ui", "panel"];
const exportsOf = (code) => [...code.matchAll(/^export (?:async )?(?:function|const|class|interface|type)\s+(\w+)/gm)].map((m) => m[1]);
function bundle(withPlugin) {
  const names = new Map(); const parts = [];
  for (const n of ORDER) {
    const raw = rd(`src/${n}.ts`); names.set(n, exportsOf(raw).filter((x) => !new RegExp(`export (?:interface|type) ${x}\\b`).test(raw)));
  }
  const declared = new Set();                 // namespace aliases already emitted (two modules may import the same one)
  for (const n of ORDER) {
    let code = rd(`src/${n}.ts`);
    code = code.replace(/^import \* as (\w+) from "\.\/(\w+)\.ts";\s*$/gm, (_, ns, mod) => { const k = `${ns}:${mod}`; if (declared.has(k)) return ""; if ([...declared].some((d) => d.startsWith(ns + ":"))) throw new Error(`alias ${ns} used for two modules`); declared.add(k); return `const ${ns} = { ${names.get(mod).join(", ")} };`; });
    code = code.replace(/^import MDSE from [^;]*;\s*$/gm, "").replace(/^import (?:type )?\{[^}]*\} from [^;]*;\s*$/gm, "").replace(/^export type \{[^}]*\}( from [^;]*)?;\s*$/gm, "")
      .replace(/^export (?=(async |function|const|class|interface|type))/gm, "");
    parts.push(`/* ${n}.ts */\n` + stripTypeScriptTypes(code, { mode: "strip" }));
  }
  const api = "{ mountWorkbench, mountPanel, LENSES, LENS_PROFILE, lensHasCanvas, lensHasTable, defaultSpec, STYLE, readZip, readFileList, readDirHandle, buildIndex, buildIndexAsync, toCanvas, pickCanvas, addToCanvas, cardNotePath, PREVIEW_DIR, PREVIEW_PATH, SAVED_DIR, PROFILES, edAuthor, edgeRefOfId, cdEdgeIds, cdDrawnLines, cdChoices, cdWhyNot, cdOtherWay, cdDropLine, cdLabelLine, planAddRelationship, edDiff }";
  return `const WB = (() => {\n${parts.join("\n")}\nreturn ${api};\n})();`;
}
const wb = bundle();
const version = JSON.parse(rd("manifest.json")).version;
let html = rd("src/workbench.template.html").replace("/*@@CORE@@*/", () => CORE).replace("/*@@WB@@*/", () => wb).replace("/*@@CLASSES@@*/", () => CLASSES);
if (/\/\*@@\w+@@\*\//.test(html)) { console.error("unreplaced placeholder"); process.exit(1); }
const plugin = `/* MDSE Workbench ${version} — generated by tools/workbench/build.mjs from tools/workbench/src. Do not edit. */\n${CORE}\nconst CLASSES = ${CLASSES};\n${wb}\n` + stripTypeScriptTypes(rd("src/plugin.ts"), { mode: "strip" });
const outputs = { "dist/mdse_workbench.html": html, "dist/plugin/main.js": plugin, "dist/plugin/manifest.json": rd("manifest.json"), "dist/plugin/styles.css": "/* styles are injected by the view */\n" };
let stale = false;
for (const [p, text] of Object.entries(outputs)) {
  const f = path.join(here, p);
  if (process.argv.includes("--check")) { if (!fs.existsSync(f) || fs.readFileSync(f, "utf8") !== text) { console.error(`${p} is out of date; run: npm run build:workbench`); stale = true; } }
  else { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, text); console.log(`wrote tools/workbench/${p} (${(text.length / 1024).toFixed(0)} KiB)`); }
}
if (stale) process.exit(1); else if (process.argv.includes("--check")) console.log("workbench output is current");
